// латинские буквы, совпадающие по начертанию с кириллическими
const LATIN_ALIAS = {
  'A': 'А', 'B': 'В', 'C': 'С', 'E': 'Е', 'H': 'Н', 'K': 'К',
  'M': 'М', 'O': 'О', 'P': 'Р', 'T': 'Т', 'X': 'Х', 'Y': 'У',
};
for (const k in LATIN_ALIAS) GLYPHS[k] = GLYPHS[LATIN_ALIAS[k]];

const Font = (() => {
  const order = Object.keys(GLYPHS);
  const index = {};
  order.forEach((ch, i) => { index[ch] = i; });

  // белый атлас
  const atlas = document.createElement('canvas');
  atlas.width = order.length * FONT_W;
  atlas.height = FONT_H;
  const actx = atlas.getContext('2d');
  actx.fillStyle = '#ffffff';
  order.forEach((ch, i) => {
    const rows = GLYPHS[ch];
    for (let y = 0; y < FONT_H; y++) {
      const row = rows[y] || '.....';
      for (let x = 0; x < FONT_W; x++) {
        if (row[x] === '#') actx.fillRect(i * FONT_W + x, y, 1, 1);
      }
    }
  });

  const tinted = {};
  function atlasFor(color) {
    if (tinted[color]) return tinted[color];
    const c = document.createElement('canvas');
    c.width = atlas.width;
    c.height = atlas.height;
    const g = c.getContext('2d');
    g.drawImage(atlas, 0, 0);
    g.globalCompositeOperation = 'source-in';
    g.fillStyle = color;
    g.fillRect(0, 0, c.width, c.height);
    tinted[color] = c;
    return c;
  }

  function norm(text) {
    return String(text).toUpperCase().replace(/Ё/g, 'Ё').replace(/…/g, '...');
  }

  function width(text, scale) {
    scale = scale || 1;
    return norm(text).length * FONT_ADV * scale - (scale ? scale : 0);
  }

  function draw(ctx, text, x, y, color, scale) {
    scale = scale || 1;
    const t = norm(text);
    const src = atlasFor(color || '#ffffff');
    let cx = Math.round(x);
    for (let i = 0; i < t.length; i++) {
      const ch = t[i];
      const gi = index[ch];
      if (gi !== undefined && ch !== ' ') {
        ctx.drawImage(src, gi * FONT_W, 0, FONT_W, FONT_H,
          cx, Math.round(y), FONT_W * scale, FONT_H * scale);
      }
      cx += FONT_ADV * scale;
    }
    return cx;
  }

  function drawCentered(ctx, text, cx, y, color, scale) {
    scale = scale || 1;
    draw(ctx, text, Math.round(cx - width(text, scale) / 2), y, color, scale);
  }

  // перенос по словам, maxW в пикселях
  function wrap(text, maxW, scale) {
    scale = scale || 1;
    const words = String(text).split(' ');
    const lines = [];
    let cur = '';
    for (const w of words) {
      const test = cur ? cur + ' ' + w : w;
      if (width(test, scale) > maxW && cur) {
        lines.push(cur);
        cur = w;
      } else {
        cur = test;
      }
    }
    if (cur) lines.push(cur);
    return lines;
  }

  return { draw, drawCentered, width, wrap, LINE: FONT_LINE, ADV: FONT_ADV, H: FONT_H };
})();
